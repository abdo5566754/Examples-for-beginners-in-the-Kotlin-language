// 3. Calculate the average of three numbers.
fun main() {

    // declaration and initial value to n1 variable
    val n1 = 188.0

    // declaration and initial value to n1 variable
    val n2 = 135.0

    // declaration and initial value to n1 variable
    val n3 = 88.0

    // declaration and calculation average to n1, n2, n3 and assignment to avg
